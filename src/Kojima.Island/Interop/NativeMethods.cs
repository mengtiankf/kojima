    /// <summary>前台窗口是否全屏独占（用于隐藏灵动岛）。</summary>
    public static bool IsForegroundFullscreen()
    {
        try
        {
            var foreground = GetForegroundWindow();
            if (foreground == IntPtr.Zero)
            {
                return false;
            }

            var shell = GetShellWindow();
            if (foreground == shell)
            {
                return false;
            }

            if (!GetWindowRect(foreground, out var windowRect))
            {
                return false;
            }

            var monitor = MonitorFromWindow(foreground, MONITOR_DEFAULTTONEAREST);
            var info = new MONITORINFO { cbSize = Marshal.SizeOf<MONITORINFO>() };
            if (!GetMonitorInfo(monitor, ref info))
            {
                return false;
            }

            return windowRect.Width >= info.rcMonitor.Width
                   && windowRect.Height >= info.rcMonitor.Height;
        }
        catch
        {
            return false;
        }
    }
